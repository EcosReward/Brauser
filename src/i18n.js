let currentLang = 'ru';

function normalizeLang(lang) {
  return lang === 'en' ? 'en' : 'ru';
}

function setLang(lang) {
  currentLang = normalizeLang(lang);
  return currentLang;
}

function getLang() {
  return currentLang;
}

function t(key, vars) {
  const table = STRINGS[currentLang] || STRINGS.ru;
  let s = table[key];
  if (s == null) s = (STRINGS.ru[key] != null ? STRINGS.ru[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = String(s).split('{' + k + '}').join(String(vars[k]));
    });
  }
  return s;
}

function tr(ru, en) {
  return currentLang === 'en' ? en : ru;
}

const api = { STRINGS, setLang, getLang, t, tr, normalizeLang };

if (typeof module !== 'undefined' && module.exports) {
  module.exports = api;
}
if (typeof window !== 'undefined') {
  window.I18n = api;
}
